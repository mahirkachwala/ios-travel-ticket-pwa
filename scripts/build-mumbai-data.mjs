import {readFile, writeFile, mkdir} from 'node:fs/promises';
const read = async name => JSON.parse(await readFile(new URL(`../sources/mumbai/${name}.json`, import.meta.url), 'utf8'));
const western = await read('western'), central = await read('central'), fares = await read('fares');
const chains = [...western.chains, ...central.chains.filter(chain => !chain.id.startsWith('memu-'))];
const aliases = {
  CSMT: ['CST','CSTM','VT','CHHATRAPATI SHIVAJI MAHARAJ TERMINUS'],
  BEPR: ['BELAPUR C.B.D','CBD BELAPUR'], SWDV: ['SWDK','SEAWOODS D K'],
  DR: ['DADAR CENTRAL'], DDR: ['DADAR WESTERN'], SVE: ['SEWREE'],
  GNSL: ['GHANSOLI'], RABE: ['RABALE'], SEMK: ['RANJANPADA','RAJANPADA'],
};
const stationMap = new Map();
for (const chain of chains) for (const item of chain.stations) {
  const old = stationMap.get(item.code);
  const name = item.code === 'DDR' ? 'DADAR WESTERN' : item.name.toUpperCase();
  stationMap.set(item.code, {
    ...old, code: item.code, name: old?.name || name,
    aliases: [...new Set([...(old?.aliases || []), ...(item.aliases || []), ...(aliases[item.code] || [])])],
    region: [...new Set([...(old?.lineNames || []), chain.name.split(':')[0]])].join(' · ').toUpperCase(),
    lineNames: [...new Set([...(old?.lineNames || []), chain.name.split(':')[0]])],
    ...(item.codeStatus ? {codeStatus: item.codeStatus} : {}),
  });
}
const dayNumber = value => typeof value === 'number' ? value : ['SUN','MON','TUE','WED','THU','FRI','SAT'].indexOf(value.slice(0,3).toUpperCase());
const acServices = [...western.acServices, ...central.acServices].map(service => ({
  ...service, directional: true,
  ...(service.lineId === 'central-main' ? {lineIds: chains.filter(chain => chain.id.startsWith('central-') && chain.stations.filter(station => service.stops.includes(station.code)).length >= 2).map(chain => chain.id)} : {}),
  days: service.days?.map(dayNumber) || null,
}));
const network = {
  schemaVersion: 1, researchedAsOf: '2026-11-02',
  scope: 'Mumbai suburban EMU: Western, Central Main and branches, Harbour, Trans-Harbour, Port/Uran. MEMU, metro, intercity and proposed routes excluded.',
  distanceMeaning: 'Published engineering chainage differences; not certified railway tariff distance.',
  stations: [...stationMap.values()].sort((a,b) => a.name.localeCompare(b.name)),
  chains, acServices,
  links: [{from:'DR',to:'DDR',km:0,lineId:'walk',sourceId:'dadar-interchange',transfer:true}],
  viaJunctions: ['DR','DDR','CLA','TNA','KYN','VDLR','MM','BA','ADH','BSR','TUH','SNCR','JNJ','NEU','SWDV','BEPR'],
  sources: [...western.sources, ...central.sources, {id:'dadar-interchange',title:'Dadar Central / Western platform interchange',url:'https://wr.indianrailways.gov.in/offerings/custom/Mumbai%20Suburban/preview/523',note:'Stations linked as a walking interchange. Zero counts railway distance only; walking distance/time are not measured.'}],
  limitations: [western.currentTimetableUncertainty, ...(western.unknowns || []), ...(central.implementationNotes || [])],
  excluded: central.excluded,
};
for (const service of network.acServices) {
  for (const code of service.stops) if (!stationMap.has(code)) throw new Error(`Unknown AC stop ${code} in ${service.id}`);
  if (service.days?.some(day => day < 0 || day > 6)) throw new Error(`Invalid day in ${service.id}`);
}
await mkdir(new URL('../dist/data/',import.meta.url),{recursive:true});
await writeFile(new URL('../dist/data/mumbai-network.js',import.meta.url), `// Generated by scripts/build-mumbai-data.mjs. Edit sources/mumbai instead.\nexport const NETWORK_DATA = ${JSON.stringify(network)};\n`);
await writeFile(new URL('../dist/data/mumbai-fares.js',import.meta.url), `// Published tariffs and explicit research gaps.\nexport const FARE_DATA = ${JSON.stringify(fares)};\n`);
console.log(`${network.stations.length} stations, ${chains.length} corridors, ${acServices.length} documented AC patterns.`);
